const CHAPTERS_BY_FORM = {
  form1: CHAPTERS_FORM1,
  form2: CHAPTERS_FORM2,
  form3: CHAPTERS_FORM3,
};

export function getChapters(formId) {
  return CHAPTERS_BY_FORM[formId] ?? [];
}

export function getChapter(formId, babId) {
  return getChapters(formId).find((b) => b.id === babId);
}

export function getTopic(formId, babId, topikId) {
  const bab = getChapter(formId, babId);
  return bab?.topics.find((t) => t.id === topikId);
}
